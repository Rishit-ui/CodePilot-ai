function detectStack(files) {
  const filePaths = new Set(files.map((f) => f.path));

  if (filePaths.has('package.json')) {
    // Check if TypeScript or Next.js
    const pkg = files.find((f) => f.path === 'package.json');
    let hasTs = filePaths.has('tsconfig.json') || files.some((f) => f.path.endsWith('.ts'));
    let isNext = pkg && pkg.content && pkg.content.includes('"next"');
    return {
      type: 'node',
      version: '20-alpine',
      hasTs,
      isNext,
      manifest: 'package.json',
      port: 3000
    };
  }

  if (filePaths.has('requirements.txt') || filePaths.has('pyproject.toml')) {
    return {
      type: 'python',
      version: '3.11-slim',
      manifest: filePaths.has('requirements.txt') ? 'requirements.txt' : 'pyproject.toml',
      port: 8000
    };
  }

  if (filePaths.has('go.mod')) {
    return {
      type: 'go',
      version: '1.22-alpine',
      manifest: 'go.mod',
      port: 8080
    };
  }

  return {
    type: 'static',
    version: 'alpine',
    port: 80
  };
}

function generateDockerfile(stack) {
  if (stack.type === 'node') {
    return `# Multi-stage production Dockerfile generated by CodePilot AI
FROM node:${stack.version} AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci --omit=dev

FROM node:${stack.version} AS runner
WORKDIR /app
ENV NODE_ENV=production
RUN addgroup -S appgroup && adduser -S appuser -G appgroup

COPY --from=builder /app/node_modules ./node_modules
COPY . .

USER appuser
EXPOSE ${stack.port}

HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
  CMD wget --no-verbose --tries=1 --spider http://localhost:${stack.port}/api/health || exit 1

CMD ["npm", "start"]
`;
  }

  if (stack.type === 'python') {
    return `# Production Dockerfile generated by CodePilot AI
FROM python:${stack.version} AS runner
WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

RUN groupadd -r appuser && useradd -r -g appuser appuser

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

COPY . .

USER appuser
EXPOSE ${stack.port}

HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
  CMD python -c "import urllib.request; urllib.request.urlopen('http://localhost:${stack.port}/health')" || exit 1

CMD ["python", "app.py"]
`;
  }

  if (stack.type === 'go') {
    return `# Multi-stage Dockerfile for Go generated by CodePilot AI
FROM golang:${stack.version} AS builder
WORKDIR /app
COPY go.* ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -o /app/server .

FROM alpine:3.19 AS runner
WORKDIR /app
RUN addgroup -S appgroup && adduser -S appuser -G appgroup
COPY --from=builder /app/server /app/server
USER appuser
EXPOSE ${stack.port}
CMD ["/app/server"]
`;
  }

  return `# Static container generated by CodePilot AI
FROM nginx:alpine
COPY . /usr/share/nginx/html
EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
`;
}

function generateDockerignore() {
  return `.git
.gitignore
node_modules
dist
build
coverage
.next
.env
.env.*
*.log
.DS_Store
.vscode
.idea
__pycache__
*.pyc
`;
}

function generateDockerCompose(projectName, stack) {
  return `version: '3.8'

services:
  web:
    build:
      context: .
      dockerfile: Dockerfile
    container_name: ${projectName.toLowerCase().replace(/[^a-z0-9_-]/g, '-')}-app
    restart: unless-stopped
    ports:
      - "${stack.port}:${stack.port}"
    environment:
      - NODE_ENV=production
      - PORT=${stack.port}
    networks:
      - app-network

networks:
  app-network:
    driver: bridge
`;
}

function diagnoseDockerFailure(exitCode, output) {
  const diag = {
    category: 'unknown',
    stage: 'build',
    remediation: 'Inspect output logs for syntax or dependency errors.'
  };

  const lower = (output || '').toLowerCase();
  if (lower.includes('npm err!') || lower.includes('could not resolve dependency') || lower.includes('pip install') && lower.includes('error:')) {
    diag.category = 'dependency_resolution';
    diag.stage = 'install_dependencies';
    diag.remediation = 'Verify dependency version compatibility and lockfile synchronization.';
  } else if (lower.includes('permission denied') || lower.includes('eacces')) {
    diag.category = 'permissions';
    diag.stage = 'runtime_user';
    diag.remediation = 'Ensure file ownership and non-root user permissions are properly configured with chown.';
  } else if (lower.includes('healthcheck') && lower.includes('unhealthy')) {
    diag.category = 'healthcheck_failure';
    diag.stage = 'readiness_probe';
    diag.remediation = 'Ensure the application starts within start-period and binds to 0.0.0.0 instead of 127.0.0.1.';
  } else if (lower.includes('port is already allocated') || lower.includes('bind: address already in use')) {
    diag.category = 'port_conflict';
    diag.stage = 'container_start';
    diag.remediation = 'Change host port mapping in docker-compose.yml or stop conflicting local service.';
  }

  return diag;
}

